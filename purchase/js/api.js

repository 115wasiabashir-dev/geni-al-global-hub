const WORKER_URL =
  'https://geni-ai-backend.wasiabashir115.workers.dev';

async function createWebCheckout(
  userId,
  packageId,
  currency = 'PKR'
) {
  const response = await fetch(
    `${WORKER_URL}/web-create-checkout`,
    {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        userId,
        packageId,
        currency
      })
    }
  );

  const data = await response.json();

  if (!response.ok) {
    throw new Error(
      data.message || 'Failed to create checkout.'
    );
  }

  return data;
}